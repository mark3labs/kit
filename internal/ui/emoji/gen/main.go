//go:build ignore

// Command gen downloads the full emoji list from emoji-api.com and writes
// data.go with a static table of shortcodes. Run it with `go generate` from
// the emoji package directory:
//
//	EMOJI_API_KEY=... go generate ./internal/ui/emoji
//
// Set EMOJI_JSON to a local file path to skip the download.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"regexp"
	"strings"
)

type apiEmoji struct {
	Slug      string `json:"slug"`
	Character string `json:"character"`
	Group     string `json:"group"`
}

// versionPrefix matches the Unicode version prefix on each slug, for example
// "e1-0-" in "e1-0-grinning-face".
var versionPrefix = regexp.MustCompile(`^e\d+-\d+-`)

// keycapNames gives the two keycaps that share the "keycap" slug a unique name.
var keycapNames = map[string]string{
	"#": "keycap_hash",
	"*": "keycap_asterisk",
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run() error {
	raw, err := load()
	if err != nil {
		return err
	}

	var list []apiEmoji
	if err := json.Unmarshal(raw, &list); err != nil {
		return fmt.Errorf("decode emoji list: %w", err)
	}
	if len(list) == 0 {
		return fmt.Errorf("emoji list is empty")
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by gen/main.go from emoji-api.com. DO NOT EDIT.\n\n")
	buf.WriteString("package emoji\n\n")
	buf.WriteString("var all = []Emoji{\n")

	seen := make(map[string]int, len(list))
	for _, e := range list {
		name := shortcode(e)
		seen[name]++
		if n := seen[name]; n > 1 {
			name = fmt.Sprintf("%s_%d", name, n)
		}
		fmt.Fprintf(&buf, "\t{Glyph: %q, Name: %q, Group: %q},\n", e.Character, name, e.Group)
	}
	buf.WriteString("}\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format data.go: %w", err)
	}
	if err := os.WriteFile("data.go", src, 0o644); err != nil {
		return fmt.Errorf("write data.go: %w", err)
	}
	fmt.Printf("gen: wrote %d emojis to data.go\n", len(list))
	return nil
}

func load() ([]byte, error) {
	if path := os.Getenv("EMOJI_JSON"); path != "" {
		data, err := os.ReadFile(path)
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", path, err)
		}
		return data, nil
	}

	key := os.Getenv("EMOJI_API_KEY")
	if key == "" {
		return nil, fmt.Errorf("set EMOJI_API_KEY or EMOJI_JSON")
	}
	resp, err := http.Get("https://emoji-api.com/emojis?access_key=" + key)
	if err != nil {
		return nil, fmt.Errorf("fetch emoji list: %w", err)
	}
	defer resp.Body.Close() //nolint:errcheck
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("fetch emoji list: status %s", resp.Status)
	}
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, fmt.Errorf("read emoji list: %w", err)
	}
	return data, nil
}

// shortcode turns an API slug such as "e0-6-flag-chad" into "flag_chad".
func shortcode(e apiEmoji) string {
	slug := versionPrefix.ReplaceAllString(e.Slug, "")
	if slug == "keycap" {
		for prefix, name := range keycapNames {
			if strings.HasPrefix(e.Character, prefix) {
				return name
			}
		}
	}
	return strings.ReplaceAll(slug, "-", "_")
}
